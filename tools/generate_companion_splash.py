"""generates the companion's themed splash icons and styles.

each phone palette gets a vector of the launcher mark in its colours, plus a splash style
the app picks on android 13+. material you uses android 14's system colours.

run from the repo root: python3 tools/generate_companion_splash.py
"""
from pathlib import Path

RES = Path('mobile/src/main/res')

BLADE = ('M54.3,19.8 H83.4 Q88.7,19.8 89.2,23.2 Q89.6,25.3 86.7,27.8 L69.5,42.8 '
         'Q65,47.3 60.5,42.8 L48.3,30.6 Q43.7,26 47.1,22.1 Q49.2,19.8 54.3,19.8 Z')
PLAY = ('M45.2,38.5 L62.1,47.7 Q66.2,50 62.1,52.3 L45.2,61.5 Q42,63.2 41.2,59.8 '
        'Q41,59.1 41,57.6 V42.4 Q41,40.9 41.2,40.2 Q42,36.8 45.2,38.5 Z')

# id -> (style suffix, blade, overlap, play, background). values logged from
# aperturePhoneScheme(option).brandPalette(); keep in sync with CompanionTheme.kt.
PALETTES = {
    'purple': ('Purple', '#6750A4', '#381E72', '#D0BCFF', '#111014'),
    'classic': ('Classic', '#5F5C63', '#1A191C', '#FFFFFF', '#111014'),
    'green': ('Green', '#006D3A', '#00391C', '#7DDA9A', '#111014'),
    'red': ('Red', '#884F48', '#51221D', '#FFB4AB', '#111014'),
    'orange': ('Orange', '#87520B', '#492900', '#FFB86B', '#111014'),
    'blue': ('Blue', '#405F90', '#0A305F', '#A9C7FF', '#111014'),
    'teal': ('Teal', '#006A66', '#003735', '#7AD6D0', '#111014'),
    'pink': ('Pink', '#894A66', '#531D37', '#FFB0D0', '#111014'),
}


def vector(blade: str, overlap: str, play: str) -> str:
    blades = ''.join(
        f'        <group android:pivotX="50" android:pivotY="50" android:rotation="{60 * k}">\n'
        f'            <path android:fillColor="{blade}" android:pathData="{BLADE}" />\n'
        f'        </group>\n'
        for k in range(6)
    )
    # overlap k: blade k+1 clipped to blade k, as in the launcher SVG.
    overlaps = ''.join(
        f'        <group android:pivotX="50" android:pivotY="50" android:rotation="{60 * k}">\n'
        f'            <clip-path android:pathData="{BLADE}" />\n'
        f'            <group android:pivotX="50" android:pivotY="50" android:rotation="60">\n'
        f'                <path android:fillColor="{overlap}" android:pathData="{BLADE}" />\n'
        f'            </group>\n'
        f'        </group>\n'
        for k in range(6)
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- generated by tools/generate_companion_splash.py, do not edit -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp"\n'
        '    android:viewportWidth="176" android:viewportHeight="176">\n'
        '    <group android:translateX="38" android:translateY="38">\n'
        f'{blades}{overlaps}'
        f'        <path android:fillColor="{play}" android:pathData="{PLAY}" />\n'
        '    </group>\n'
        '</vector>\n'
    )


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


for pid, (_, blade, overlap, play, _) in PALETTES.items():
    write(RES / f'drawable/splash_mark_{pid}.xml', vector(blade, overlap, play))

# Material You: purple fallback below Android 14, then system role colours.
purple = PALETTES['purple']
write(RES / 'drawable/splash_mark_material_you.xml', vector(purple[1], purple[2], purple[3]))
write(RES / 'drawable-v34/splash_mark_material_you.xml', vector(
    '@android:color/system_inverse_primary_light',
    '@android:color/system_on_primary_light',
    '@android:color/system_primary_light'))
write(RES / 'drawable-night-v34/splash_mark_material_you.xml', vector(
    '@android:color/system_inverse_primary_dark',
    '@android:color/system_on_primary_dark',
    '@android:color/system_primary_dark'))

colors = lambda value: ('<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tools/generate_companion_splash.py -->\n'
                        f'<resources>\n    <color name="splash_background_material_you">{value}</color>\n</resources>\n')
write(RES / 'values/splash_colors.xml', colors(purple[4]))
write(RES / 'values-v34/splash_colors.xml', colors('@android:color/system_background_light'))
write(RES / 'values-night-v34/splash_colors.xml', colors('@android:color/system_background_dark'))

styles = ['<?xml version="1.0" encoding="utf-8"?>',
          '<!-- generated by tools/generate_companion_splash.py, do not edit -->',
          '<resources>']
for pid, (suffix, _, _, _, background) in PALETTES.items():
    styles += [f'    <style name="Theme.ApertureCompanion.Splash.{suffix}" parent="Theme.ApertureCompanion">',
               f'        <item name="android:windowSplashScreenBackground">{background}</item>',
               f'        <item name="android:windowSplashScreenAnimatedIcon">@drawable/splash_mark_{pid}</item>',
               '    </style>']
styles += ['    <style name="Theme.ApertureCompanion.Splash.MaterialYou" parent="Theme.ApertureCompanion">',
           '        <item name="android:windowSplashScreenBackground">@color/splash_background_material_you</item>',
           '        <item name="android:windowSplashScreenAnimatedIcon">@drawable/splash_mark_material_you</item>',
           '    </style>',
           '</resources>', '']
write(RES / 'values-v31/splash_themes.xml', '\n'.join(styles))
print('Generated splash assets for', ', '.join([*PALETTES, 'material_you']))
